# Builds OB1/integrations/research-service/boundary-lexicon.ts from SCOWL 2020.12.07 (final/ word lists).
# rw-boundary-core (plan 09 D11): the request boundary gate's lexicon - a reviewed, hashed, checked-in list.
#   1. download scowl-2020.12.07.tar.gz (https://sourceforge.net/projects/wordlist/files/SCOWL/2020.12.07/) into
#      an empty directory and check its sha256 (5587667caa20c4891390c2d42dbb4d5c4c3f41bee77af1457ece3ba23fb859cc)
#   2. tar xzf it there
#   3. python -I build-boundary-lexicon.py <dir>/scowl-2020.12.07/final ../boundary-lexicon.ts <the tarball sha256>
# The output is byte-identical for the same tarball (sorted, LF); boundary-gate.test.ts checks LEXICON_SHA256.
import hashlib, re, sys, unicodedata
final, out, tarsha = sys.argv[1], sys.argv[2], sys.argv[3]
LEVELS = [10, 20, 35, 40, 50]
words = set()
dropped = 0
tok = re.compile(r"^[^\W_]+$", re.UNICODE)
for cat in ("english-words", "american-words"):
    for n in LEVELS:
        try:
            raw = open(f"{final}/{cat}.{n}", "rb").read().decode("iso-8859-1")
        except FileNotFoundError:
            continue
        for line in raw.splitlines():
            w = line.strip()
            if not w:
                continue
            if w != w.lower():          # any capital = a proper noun / acronym class entry: never
                dropped += 1; continue
            w = unicodedata.normalize("NFKC", w).lower()
            if not tok.match(w):        # possessives, hyphenated, dotted: not one gate token
                dropped += 1; continue
            words.add(w)
lst = sorted(words)
body = "\n".join(lst)
sha = hashlib.sha256(body.encode("utf-8")).hexdigest()
notice = open(f"{final}/../Copyright", "rb").read().decode("iso-8859-1").split("\n")[:13]
with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("// GENERATED by the rw-boundary-core lexicon build - do not edit by hand; a change is a reviewed commit\n")
    f.write("// (plan 09 D11). The boundary gate's LEXICON (boundary-gate.ts): common English words, no proper nouns.\n")
    f.write("//\n")
    f.write("// Source: SCOWL (Spell Checker Oriented Word Lists) 2020.12.07, http://wordlist.aspell.net/\n")
    f.write(f"//   tarball scowl-2020.12.07.tar.gz sha256 {tarsha}\n")
    f.write(f"//   final/english-words.N + final/american-words.N for N in {LEVELS} (SCOWL's size classes are\n")
    f.write("//   frequency classes: 10 = the most common words ... 50 = the common-vocabulary boundary); entries with any\n")
    f.write("//   capital letter (SCOWL's proper-name / upper classes are separate files and are not read) and entries that\n")
    f.write(r"//   are not one [\p{L}\p{N}]+ token (possessives, hyphenated) are dropped; NFKC + lowercase, sorted, unique." + "\n")
    f.write(f"//   {len(lst)} words; {dropped} source lines dropped.\n")
    f.write("// SCOWL's license (permissive, compatible with this repository's FSL-1.1-MIT) requires this notice:\n")
    for l in notice:
        f.write(("//   " + l).rstrip() + "\n")
    f.write("//   (the full notice, with the public-domain statements of SCOWL's sources: SCOWL's Copyright file)\n")
    f.write("\n")
    f.write('export const LEXICON_SOURCE = "scowl-2020.12.07:english+american:10-50";\n')
    f.write("/** sha256 of the word list joined by LF (UTF-8; the CRs of a CRLF checkout are dropped first) - boundary-gate.test.ts recomputes it; the lexicon version is this hash. */\n")
    f.write(f'export const LEXICON_SHA256 = "{sha}";\n')
    f.write(f"export const LEXICON_COUNT = {len(lst)};\n")
    f.write("export const LEXICON_WORDS = `" + body + "`;\n")
print(len(lst), dropped, sha)
