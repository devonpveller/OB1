// The contract's generated artifacts, from the routes themselves:
//   generated/openapi.json   the OpenAPI 3.0.3 document (what GET /openapi.json serves)
//   generated/types.ts       TypeScript types for every component schema (for panels and clients)
//   generated/mcp-tools.json the read operations openbrain-mcp registers as tools (D14: reads only)
// and a copy of mcp-tools.json beside openbrain-mcp (integrations/kubernetes-deployment/
// contract-tools.json), the adapter's input. `--check` regenerates in memory and FAILS when a
// committed file differs, so the document, the types and the MCP tools cannot drift apart.
//
//   deno task contract:gen      (writes)       deno task contract:check   (verifies)
import { createContractApp, openApiDocument } from "./app.ts";
import { RegistryReader } from "./registry.ts";
import { unavailableScorer } from "./logic/reopen.ts";
import type { Db } from "./db.ts";

type Schema = Record<string, unknown>;

const here = new URL(".", import.meta.url);
const OUT = {
  openapi: new URL("generated/openapi.json", here),
  types: new URL("generated/types.ts", here),
  mcp: new URL("generated/mcp-tools.json", here),
  mcpCopy: new URL("../../../../integrations/kubernetes-deployment/contract-tools.json", here),
};

// Route registration never touches the database; the generator runs with none.
const noDb: Db = {
  query: () => Promise.reject(new Error("the generator has no database")),
  tx: () => Promise.reject(new Error("the generator has no database")),
};

export function buildDocument(): Schema {
  const app = createContractApp({
    db: noDb, registry: new RegistryReader(noDb), scorer: unavailableScorer,
    embed: () => Promise.reject(new Error("no embedder")), chunk: () => [], mountsRoot: "/mounts",
    streamPollMs: 1000, log: () => {},
  });
  return openApiDocument(app) as unknown as Schema;
}

// ── TypeScript emitter (the JSON-schema subset the contract uses: objects, arrays, scalars,
// nullable, additionalProperties, $ref - the conformance test forbids enum/anyOf/allOf/oneOf).
const refName = (r: string) => r.split("/").pop()!;

function tsType(s: Schema, pad: string): string {
  let t: string;
  if (typeof s.$ref === "string") t = refName(s.$ref);
  else if (s.type === "object" && s.properties) t = tsObject(s, pad);
  else if (s.type === "object") {
    const ap = s.additionalProperties as Schema | boolean | undefined;
    t = `Record<string, ${ap && typeof ap === "object" && ap.type ? tsType(ap, pad) : "unknown"}>`;
  } else if (s.type === "array") t = `Array<${tsType((s.items ?? {}) as Schema, pad)}>`;
  else if (s.type === "integer" || s.type === "number") t = "number";
  else if (s.type === "string") t = "string";
  else if (s.type === "boolean") t = "boolean";
  else t = "unknown";
  return s.nullable ? `${t} | null` : t;
}

function tsObject(s: Schema, pad: string): string {
  const req = new Set((s.required as string[]) ?? []);
  const props = s.properties as Record<string, Schema>;
  const lines = Object.entries(props).map(([k, p]) => {
    const reg = typeof p["x-registry"] === "string" ? ` /** registry: ${p["x-registry"]} */` : "";
    return `${pad}  ${k}${req.has(k) ? "" : "?"}: ${tsType(p, pad + "  ")};${reg}`;
  });
  return `{\n${lines.join("\n")}\n${pad}}`;
}

export function buildTypes(doc: Schema): string {
  const schemas = ((doc.components as Schema).schemas ?? {}) as Record<string, Schema>;
  const out = [
    "// GENERATED by src/contracts/gen.ts from the retrieval contract's OpenAPI document. Do not edit:",
    "// change the zod schemas in src/contracts/schemas/ and run `deno task contract:gen`.",
    "// A field annotated `registry:` holds a key of that registry (GET /workbench/contract/registries/<name>).",
    "",
  ];
  for (const name of Object.keys(schemas).sort()) out.push(`export type ${name} = ${tsType(schemas[name], "")};`, "");
  return out.join("\n");
}

// ── MCP manifest: the read operations, with inputs flattened into one property bag ─────────
function deref(s: unknown, doc: Schema, seen = new Set<string>()): unknown {
  if (Array.isArray(s)) return s.map((x) => deref(x, doc, seen));
  if (!s || typeof s !== "object") return s;
  const o = s as Schema;
  if (typeof o.$ref === "string") {
    const n = refName(o.$ref);
    if (seen.has(n)) throw new Error(`recursive schema ${n} cannot be inlined for MCP`);
    const target = ((doc.components as Schema).schemas as Record<string, Schema>)[n];
    return deref(target, doc, new Set([...seen, n]));
  }
  return Object.fromEntries(Object.entries(o).filter(([k]) => k !== "example").map(([k, v]) => [k, deref(v, doc, seen)]));
}

export interface McpToolSpec {
  tool: string;
  operationId: string;
  method: string;
  path: string;
  description: string;
  input: { type: "object"; properties: Record<string, Schema>; required: string[] };
  path_params: string[];
  query_params: string[];
  json_params: string[]; // query params that carry a JSON object (sent as an object over MCP)
  body_params: string[];
}

export function buildMcp(doc: Schema): McpToolSpec[] {
  const tools: McpToolSpec[] = [];
  for (const [path, item] of Object.entries(doc.paths as Record<string, Record<string, Schema>>)) {
    for (const [method, op] of Object.entries(item)) {
      if (typeof op["x-mcp-tool"] !== "string") continue;
      tools.push(mcpSpec(doc, path, method, op));
    }
  }
  return tools.sort((a, b) => a.tool.localeCompare(b.tool));
}

function mcpSpec(doc: Schema, path: string, method: string, op: Schema): McpToolSpec {
  const props: Record<string, Schema> = {};
  const required: string[] = [];
  const spec = { path_params: [] as string[], query_params: [] as string[], json_params: [] as string[], body_params: [] as string[] };
  for (const p of (op.parameters as Schema[] | undefined) ?? []) {
    const name = p.name as string;
    const isJson = name === "metadata_filter";
    props[name] = isJson
      ? { type: "object", additionalProperties: {}, description: p.schema && (p.schema as Schema).description || "" }
      : { ...(deref(p.schema, doc) as Schema), description: String((p.schema as Schema)?.description ?? p.description ?? "") };
    if (p.required) required.push(name);
    (p.in === "path" ? spec.path_params : isJson ? spec.json_params : spec.query_params).push(name);
  }
  const body = (((op.requestBody as Schema)?.content as Schema)?.["application/json"] as Schema)?.schema;
  if (body) {
    const b = deref(body, doc) as Schema;
    for (const [k, v] of Object.entries((b.properties ?? {}) as Record<string, Schema>)) {
      if (props[k]) throw new Error(`${op.operationId}: body field ${k} collides with a parameter`);
      props[k] = v;
      spec.body_params.push(k);
    }
    for (const r of (b.required as string[]) ?? []) required.push(r);
  }
  return {
    tool: op["x-mcp-tool"] as string, operationId: op.operationId as string, method: method.toUpperCase(), path,
    description: `${op.summary ?? ""} [retrieval contract ${method.toUpperCase()} ${path}]`,
    input: { type: "object", properties: props, required }, ...spec,
  };
}

const stable = (v: unknown) => JSON.stringify(v, null, 2) + "\n";

export function buildAll(): Record<keyof typeof OUT, string> {
  const doc = buildDocument();
  const mcp = stable(buildMcp(doc));
  return { openapi: stable(doc), types: buildTypes(doc), mcp, mcpCopy: mcp };
}

async function readOrNull(u: URL): Promise<string | null> {
  try {
    return await Deno.readTextFile(u);
  } catch {
    return null;
  }
}

if (import.meta.main) {
  const check = Deno.args.includes("--check");
  const files = buildAll();
  const stale: string[] = [];
  for (const [k, text] of Object.entries(files) as [keyof typeof OUT, string][]) {
    const u = OUT[k];
    const current = await readOrNull(u);
    // The MCP copy lives outside the workbench image's build context: absent there, not stale.
    if (k === "mcpCopy" && current === null && check) continue;
    if (check) {
      if (current?.replace(/\r\n/g, "\n") !== text) stale.push(u.pathname);
    } else {
      await Deno.writeTextFile(u, text);
    }
  }
  if (check && stale.length) {
    console.error(`contract artifacts are stale (run \`deno task contract:gen\`):\n  ${stale.join("\n  ")}`);
    Deno.exit(1);
  }
  console.log(check ? "contract artifacts are current" : `wrote ${Object.keys(files).length} contract artifacts`);
}
