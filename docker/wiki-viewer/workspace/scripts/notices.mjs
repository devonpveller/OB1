// The workspace's third-party notices (D9 rule 5: one notices file, generated at build and checked).
// Reads package-lock.json - every package the SHIPPED bundle can contain (not dev) - and each one's
// own package.json licence and licence text from node_modules, as installed by `npm ci` from the
// lockfile. Refuses any licence outside the permissive allow-list (D9).
//   node scripts/notices.mjs           write THIRD-PARTY-NOTICES.md
//   node scripts/notices.mjs --check   fail when the file is not what the lockfile gives, or a licence is refused
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ALLOW = new Set(["MIT", "Apache-2.0", "BSD-2-Clause", "BSD-3-Clause", "ISC", "0BSD", "MPL-2.0", "BSD-2-Clause-Patent"]);
const lock = JSON.parse(readFileSync("package-lock.json", "utf8"));
const rows = [];
const refused = [];
for (const [key, meta] of Object.entries(lock.packages)) {
  if (!key || meta.dev) continue;
  const name = key.replace(/^.*node_modules\//, "");
  const dir = key;
  const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
  const license = typeof pkg.license === "string" ? pkg.license : pkg.license?.type ?? "UNKNOWN";
  if (!ALLOW.has(license)) refused.push(`${name}@${pkg.version}: ${license}`);
  const file = readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(f));
  const text = file ? readFileSync(join(dir, file), "utf8").replace(/\r\n/g, "\n").trim() : `(no licence file in the package; package.json says ${license})`;
  rows.push({ name, version: pkg.version, license, text });
}
rows.sort((a, b) => a.name.localeCompare(b.name));
const out = [
  "# Third-party notices - the workspace (research-workbench P2b)",
  "",
  "GENERATED by `node scripts/notices.mjs` from package-lock.json; `--check` runs in the viewer image build.",
  "Every package below can be part of the shipped /workspace bundle; each keeps its notice here (D9 rule 5).",
  "",
  "| package | version | licence |",
  "|---|---|---|",
  ...rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} |`),
  "",
  ...rows.flatMap((r) => [`## ${r.name} ${r.version} (${r.license})`, "", "```", r.text, "```", ""]),
].join("\n");

if (refused.length) {
  console.error(`REFUSED (D9 - not a permissive licence):\n  ${refused.join("\n  ")}`);
  process.exit(1);
}
if (process.argv.includes("--check")) {
  const cur = existsSync("THIRD-PARTY-NOTICES.md") ? readFileSync("THIRD-PARTY-NOTICES.md", "utf8").replace(/\r\n/g, "\n") : "";
  if (cur !== out) {
    console.error("THIRD-PARTY-NOTICES.md is not what package-lock.json gives: run `node scripts/notices.mjs`");
    process.exit(1);
  }
  console.log(`notices: ${rows.length} packages, every licence permissive, the file is current`);
} else {
  writeFileSync("THIRD-PARTY-NOTICES.md", out);
  console.log(`wrote THIRD-PARTY-NOTICES.md (${rows.length} packages)`);
}
