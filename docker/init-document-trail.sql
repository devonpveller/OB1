-- ============================================================
-- The user documents' removal trail (research-workbench redesign, rwr-docs-lifecycle-api; Q9).
--
-- What this file adds, and only this (a line per removal for good, and per document put back):
--   user_document_trail  one row per user document removed for good: delete forever (one trashed
--                        document), empty trash (the caller's own trash), or the nightly run (a
--                        document trashed more than 30 days ago). owner_sub is the document's owner;
--                        actor_sub is who removed it (the owner, an admin, or the fixed system actor
--                        'system:nightly'). The row names the document - its id and vault path - and
--                        never a body or a title.
--
-- Why a table of its own and not source_trail_events: that trail belongs to SHARED knowledge (a source's
-- history, keyed by a source id, read by every user's research view). A user document is front-end
-- context, private to its owner (operator 2026-10-28), so its removal line lives in a per-owner store
-- read only through the identity seam (GET /workbench/documents/trail). The vault commit of the removal
-- (git rm) stays the recoverable record of the text itself.
--
-- Idempotent (IF NOT EXISTS); re-running it changes nothing. Fresh-volume slot 510; the live DB gets it
-- by hand (psql -f, BEFORE the new workbench image, a fresh backup first).
-- Revert: revert-document-trail.sql (THIS DISCARDS the trail rows); revert-document-trail-grants.sql puts back only the
-- first version's grants (ALL to service_role, no trigger) and keeps the rows.
-- ============================================================

BEGIN;  -- one transaction (rwr-trail-grants-exact F3): the REVOKE, the GRANT and the triggers land together or not at all

CREATE TABLE IF NOT EXISTS public.user_document_trail (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_sub   TEXT NOT NULL,           -- whose document it was (the listing row's owner; the identity seam's subject)
    actor_sub   TEXT NOT NULL,           -- who removed it: the owner, an admin, or 'system:nightly'
    kind        TEXT NOT NULL CHECK (kind IN ('delete_forever', 'empty_trash', 'nightly_expired', 'restored', 'unarchived')),
    document_id UUID,                    -- the listing row's id, when the document was listed
    path        TEXT NOT NULL,           -- the vault path it had (documents/<owner key>/.trash/...); never its text or title
    trashed_at  TIMESTAMPTZ,             -- when it went into the trash, when that was known
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
-- rwr-trail-grants-exact: the trail also records a document put back (restored from the trash, unarchived), so the kind
-- CHECK is wider than the first version of this slot made it. A database that ran the first version still has the narrow
-- constraint (CREATE TABLE IF NOT EXISTS leaves it): replace it by name. Re-runnable.
ALTER TABLE public.user_document_trail DROP CONSTRAINT IF EXISTS user_document_trail_kind_check;
ALTER TABLE public.user_document_trail ADD CONSTRAINT user_document_trail_kind_check
    CHECK (kind IN ('delete_forever', 'empty_trash', 'nightly_expired', 'restored', 'unarchived'));
CREATE INDEX IF NOT EXISTS idx_user_document_trail_owner ON public.user_document_trail (owner_sub, created_at DESC);

-- -- RLS + grants: append-only for the app (rwr-trail-grants-exact; review F-1 of rwr-docs-lifecycle-api-r2) --
ALTER TABLE public.user_document_trail ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS user_document_trail_service_role_all ON public.user_document_trail;
CREATE POLICY user_document_trail_service_role_all ON public.user_document_trail FOR ALL TO service_role USING (true) WITH CHECK (true);
-- The schema's default privileges (init-grants.sql) hand every new table ALL to service_role, so a plain GRANT would
-- leave UPDATE, TRUNCATE and DELETE in place. Take back every direct grant first (PUBLIC, service_role, any other role:
-- slots 470 and 570 do the same), then grant exactly what the app needs: read and add. Nothing in OB1 deletes or edits a
-- trail line (the nightly run removes documents, never trail lines); a future per-user erasure gets its own owner-scoped
-- function. Re-running it on a database that already ran an earlier version of this slot converges to the same ACL.
REVOKE ALL ON public.user_document_trail FROM PUBLIC;
DO $$
DECLARE r RECORD;
BEGIN
    FOR r IN SELECT DISTINCT ro.rolname AS grantee
               FROM pg_class cl, aclexplode(cl.relacl) a JOIN pg_roles ro ON ro.oid = a.grantee
              WHERE cl.oid = 'public.user_document_trail'::regclass AND NOT ro.rolsuper AND ro.oid <> cl.relowner
    LOOP
        EXECUTE format('REVOKE ALL ON public.user_document_trail FROM %I', r.grantee);
    END LOOP;
END $$;
GRANT SELECT, INSERT ON public.user_document_trail TO service_role;

-- The grant is the first layer; this is the second (admin_audit's shape): a line is never edited or deleted and the table is
-- never wiped, by any role, even one that is later granted UPDATE, DELETE or TRUNCATE (a superuser must drop the trigger on purpose).
CREATE OR REPLACE FUNCTION public.user_document_trail_no_edit() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'user_document_trail is append-only for the app (% refused)', TG_OP USING ERRCODE = 'insufficient_privilege';
END $$;
REVOKE ALL ON FUNCTION public.user_document_trail_no_edit() FROM PUBLIC;
DROP TRIGGER IF EXISTS trg_user_document_trail_no_update ON public.user_document_trail;
-- statement-level, so the refusal does not depend on row-level security showing the caller a row
CREATE TRIGGER trg_user_document_trail_no_update BEFORE UPDATE ON public.user_document_trail
    FOR EACH STATEMENT EXECUTE FUNCTION public.user_document_trail_no_edit();
DROP TRIGGER IF EXISTS trg_user_document_trail_no_truncate ON public.user_document_trail;
CREATE TRIGGER trg_user_document_trail_no_truncate BEFORE TRUNCATE ON public.user_document_trail
    FOR EACH STATEMENT EXECUTE FUNCTION public.user_document_trail_no_edit();
-- DELETE too (statement-level: a DELETE with no WHERE, or one RLS shows no rows, is refused as well)
DROP TRIGGER IF EXISTS trg_user_document_trail_no_delete ON public.user_document_trail;
CREATE TRIGGER trg_user_document_trail_no_delete BEFORE DELETE ON public.user_document_trail
    FOR EACH STATEMENT EXECUTE FUNCTION public.user_document_trail_no_edit();
-- this table's own sequence only (round 2, F7): nothing else in the schema is touched, so the revert is exact
GRANT USAGE, SELECT ON SEQUENCE public.user_document_trail_id_seq TO service_role;

COMMIT;
NOTIFY pgrst, 'reload schema';
